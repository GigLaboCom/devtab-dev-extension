/**
 * Checksums the archive needs while it streams: SHA-256 (FIPS 180-4) fed chunk by chunk — WebCrypto's digest takes one
 * whole buffer, which would hold a large file of the archive in memory at once — and CRC-32 (the ZIP format's, IEEE
 * 802.3 polynomial). Both are checked against WebCrypto and known values in checksums.test.ts. Blobs, whose size is
 * bounded, are hashed with WebCrypto directly (sha256Hex).
 */
